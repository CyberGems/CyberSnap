param([int]$RdpProcessId, [string]$OutputPath)
$ErrorActionPreference = 'Stop'
if ($env:GITHUB_ACTIONS -ne 'true' -or $env:RUNNER_ENVIRONMENT -ne 'github-hosted') {
    throw 'RDP diagnostics require the disposable test VM.'
}
Add-Type -AssemblyName UIAutomationClient
Add-Type -AssemblyName UIAutomationTypes
Add-Type -Path "$PSScriptRoot\WindowsSession.cs"
$client = Get-CimInstance Win32_Process -Filter "ProcessId=$RdpProcessId"
if ($client.Name -ne 'mstsc.exe' -or $client.CommandLine -notmatch '(?:^|\s)/v:127\.0\.0\.2(?:\s|$)') {
    throw 'Only the loopback RDP client launched by this test may be initialized.'
}
$condition = [Windows.Automation.PropertyCondition]::new([Windows.Automation.AutomationElement]::ProcessIdProperty, $RdpProcessId)
$windows = [Windows.Automation.AutomationElement]::RootElement.FindAll([Windows.Automation.TreeScope]::Children, $condition)
$messages = foreach ($window in $windows) {
    $controls = $window.FindAll([Windows.Automation.TreeScope]::Descendants, [Windows.Automation.Condition]::TrueCondition)
    $labels = @($controls | Where-Object { -not $_.Current.IsPassword -and $_.Current.ControlType -ne [Windows.Automation.ControlType]::Edit } | ForEach-Object { $_.Current.Name })
    $text = $labels -join "`n"
    # The April 2026 first-use notice blocks RDP-file connections. This file was
    # generated by the test for loopback, with resource redirection disabled.
    if ($text -match 'Opening Remote Desktop Connection' -and $text -notmatch '127\.0\.0\.2') {
        $acknowledgements = @($controls | Where-Object { $_.Current.ControlType -eq [Windows.Automation.ControlType]::CheckBox })
        if ($acknowledgements.Count -eq 1) {
            $toggle = [Windows.Automation.TogglePattern]$acknowledgements[0].GetCurrentPattern([Windows.Automation.TogglePattern]::Pattern)
            if ($toggle.Current.ToggleState -eq [Windows.Automation.ToggleState]::Off) { $toggle.Toggle() }
            Start-Sleep -Milliseconds 200
            [InstallerTestSession]::ClickDialogButton($RdpProcessId, 'OK') | Out-Null
        }
    } elseif ($text -match '127\.0\.0\.2|Caution: Unknown remote connection') {
        # Leave all resource-sharing checkboxes off.
        [InstallerTestSession]::ClickDialogButton($RdpProcessId, 'Connect') | Out-Null
    }
    foreach ($control in $controls) {
        try { $current = $control.Current } catch [Windows.Automation.ElementNotAvailableException] { continue }
        # Only metadata in this RDP client's windows, never credential edit values.
        if (-not $current.IsPassword -and $current.ControlType -ne [Windows.Automation.ControlType]::Edit -and $current.Name) {
            [ordered]@{ Type = $current.ControlType.ProgrammaticName; Name = $current.Name }
        }
    }
}
@($messages) | ConvertTo-Json | Set-Content -LiteralPath $OutputPath
